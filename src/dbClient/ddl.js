// CREATE statements for PostgreSQL tables, put together from catalog rows (PostgreSQL has no
// SHOW CREATE TABLE). Pure text building: the driver reads the rows, this turns them into DDL.
// MySQL needs none of this: the server writes its own DDL.

const quote = (name) => `"${String(name).replace(/"/g, '""')}"`
const literal = (text) => `'${String(text).replace(/'/g, "''")}'`

/**
 * @param {string} schema
 * @param {object} catalog rows read by the driver
 * @param {Array<{ table: string, kind: string, comment: string|null, viewDefinition: string|null }>} catalog.tables
 *   kind: r / p (table), v (view), m (materialized view), f (foreign table)
 * @param {Array<{ table: string, name: string, type: string, isNotNull: boolean, defaultValue: string|null, identity: string, comment: string|null }>} catalog.columns
 *   in column order; identity: '' | 'a' (always) | 'd' (by default)
 * @param {Array<{ table: string, name: string, definition: string }>} catalog.constraints
 * @param {Array<{ table: string, definition: string }>} catalog.indexes (those not made by a constraint)
 * @returns {string} the statements, tables in the order given
 */
function buildPostgresDdl(schema, { tables, columns, constraints, indexes }) {
  const by = (rows) => {
    const map = new Map()
    for (const row of rows) {
      if (!map.has(row.table)) map.set(row.table, [])
      map.get(row.table).push(row)
    }
    return map
  }
  const columnsOf = by(columns)
  const constraintsOf = by(constraints)
  const indexesOf = by(indexes)

  const parts = tables.map(({ table, kind, comment, viewDefinition }) => {
    const name = `${quote(schema)}.${quote(table)}`
    const tableColumns = columnsOf.get(table) ?? []
    const statements = []

    if (kind === 'v' || kind === 'm') {
      const body = String(viewDefinition ?? '').trim().replace(/;\s*$/, '')
      statements.push(`CREATE ${kind === 'm' ? 'MATERIALIZED VIEW' : 'VIEW'} ${name} AS\n${body};`)
    } else {
      const lines = tableColumns.map((column) => {
        let line = `  ${quote(column.name)} ${column.type}`
        if (column.identity === 'a') line += ' GENERATED ALWAYS AS IDENTITY'
        else if (column.identity === 'd') line += ' GENERATED BY DEFAULT AS IDENTITY'
        else if (column.defaultValue !== null && column.defaultValue !== undefined) line += ` DEFAULT ${column.defaultValue}`
        if (column.isNotNull) line += ' NOT NULL'
        return line
      })
      for (const constraint of constraintsOf.get(table) ?? []) lines.push(`  CONSTRAINT ${quote(constraint.name)} ${constraint.definition}`)
      statements.push(`CREATE ${kind === 'f' ? 'FOREIGN TABLE' : 'TABLE'} ${name} (\n${lines.join(',\n')}\n);`)
    }

    for (const index of indexesOf.get(table) ?? []) statements.push(`${String(index.definition).replace(/;\s*$/, '')};`)
    const target = kind === 'v' ? 'VIEW' : kind === 'm' ? 'MATERIALIZED VIEW' : kind === 'f' ? 'FOREIGN TABLE' : 'TABLE'
    if (comment) statements.push(`COMMENT ON ${target} ${name} IS ${literal(comment)};`)
    for (const column of tableColumns) {
      if (column.comment) statements.push(`COMMENT ON COLUMN ${name}.${quote(column.name)} IS ${literal(column.comment)};`)
    }
    return statements.join('\n')
  })
  return parts.join('\n\n') + (parts.length > 0 ? '\n' : '')
}

module.exports = { buildPostgresDdl }
