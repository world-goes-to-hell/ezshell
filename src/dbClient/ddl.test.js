import { describe, it, expect } from 'vitest'
import { buildPostgresDdl } from './ddl.js'

describe('buildPostgresDdl', () => {
  it('writes a table with defaults, constraints, indexes and comments', () => {
    const ddl = buildPostgresDdl('public', {
      tables: [{ table: 'orders', kind: 'r', comment: '주문', viewDefinition: null }],
      columns: [
        { table: 'orders', name: 'id', type: 'integer', isNotNull: true, defaultValue: null, identity: 'd', comment: null },
        { table: 'orders', name: 'customer_id', type: 'integer', isNotNull: true, defaultValue: null, identity: '', comment: '고객 "번호"' },
        { table: 'orders', name: 'amount', type: 'numeric(10,2)', isNotNull: false, defaultValue: '0', identity: '', comment: null },
        { table: 'orders', name: 'created', type: 'timestamp without time zone', isNotNull: true, defaultValue: 'now()', identity: '', comment: null }
      ],
      constraints: [
        { table: 'orders', name: 'orders_pkey', definition: 'PRIMARY KEY (id)' },
        { table: 'orders', name: 'orders_customer_fk', definition: 'FOREIGN KEY (customer_id) REFERENCES customers(id)' }
      ],
      indexes: [{ table: 'orders', definition: 'CREATE INDEX orders_created_idx ON public.orders USING btree (created)' }]
    })
    expect(ddl).toBe([
      'CREATE TABLE "public"."orders" (',
      '  "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
      '  "customer_id" integer NOT NULL,',
      '  "amount" numeric(10,2) DEFAULT 0,',
      '  "created" timestamp without time zone DEFAULT now() NOT NULL,',
      '  CONSTRAINT "orders_pkey" PRIMARY KEY (id),',
      '  CONSTRAINT "orders_customer_fk" FOREIGN KEY (customer_id) REFERENCES customers(id)',
      ');',
      'CREATE INDEX orders_created_idx ON public.orders USING btree (created);',
      'COMMENT ON TABLE "public"."orders" IS \'주문\';',
      'COMMENT ON COLUMN "public"."orders"."customer_id" IS \'고객 "번호"\';',
      ''
    ].join('\n'))
  })

  it('writes views from their definition and separates objects with a blank line', () => {
    const ddl = buildPostgresDdl('app', {
      tables: [
        { table: 'paid', kind: 'v', comment: null, viewDefinition: ' SELECT id FROM orders WHERE paid;' },
        { table: 'totals', kind: 'm', comment: null, viewDefinition: 'SELECT 1' },
        { table: 't', kind: 'r', comment: null, viewDefinition: null }
      ],
      columns: [{ table: 't', name: 'a', type: 'text', isNotNull: false, defaultValue: null, identity: '', comment: null }],
      constraints: [],
      indexes: []
    })
    expect(ddl).toBe([
      'CREATE VIEW "app"."paid" AS',
      'SELECT id FROM orders WHERE paid;',
      '',
      'CREATE MATERIALIZED VIEW "app"."totals" AS',
      'SELECT 1;',
      '',
      'CREATE TABLE "app"."t" (',
      '  "a" text',
      ');',
      ''
    ].join('\n'))
  })

  it('quotes names and comment text that contain quotes, and is empty for nothing', () => {
    const ddl = buildPostgresDdl('my"schema', {
      tables: [{ table: 'we"ird', kind: 'r', comment: "it's", viewDefinition: null }],
      columns: [{ table: 'we"ird', name: 'col', type: 'integer', isNotNull: false, defaultValue: null, identity: 'a', comment: null }],
      constraints: [],
      indexes: []
    })
    expect(ddl).toContain('CREATE TABLE "my""schema"."we""ird" (\n  "col" integer GENERATED ALWAYS AS IDENTITY\n);')
    expect(ddl).toContain('COMMENT ON TABLE "my""schema"."we""ird" IS \'it\'\'s\';')
    expect(buildPostgresDdl('public', { tables: [], columns: [], constraints: [], indexes: [] })).toBe('')
  })
})
